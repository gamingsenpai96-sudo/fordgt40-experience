  async loadModel() {
    const loader = createGLTFLoader();

    if (!window.__GT40_GLTF_PROMISE__) {
      window.__GT40_GLTF_PROMISE__ = new Promise((resolve, reject) => {
        loader.load(
          'assets/models/car/source/gt40.glb',
          (gltf) => resolve(gltf),
          (p) => {
            if (p.total && this.loaderFill) {
              const pct = Math.min(100, Math.round((p.loaded / p.total) * 100));
              this.loaderFill.style.width = `${pct}%`;
              if (this.loaderSub) this.loaderSub.textContent = `Streaming GT40 Mk II Geometry (${pct}%)`;
            }
          },
          (err) => reject(err)
        );
      });
    }

    return window.__GT40_GLTF_PROMISE__.then((gltf) => {
      if (this.isInitialized) return;
      this.modelRoot = gltf.scene.clone(true);
      this.setupMaterialsAndMeshes();
      this.createMechanicalAssemblies();
      this.scene.add(this.modelRoot);

      if (this.loader) {
        this.loader.classList.add('hidden');
      }

      this.isInitialized = true;
      if (this.isXRay && this.parts.body && this.bodyXRayMaterial) {
        this.parts.body.material = this.bodyXRayMaterial;
      }
      this.updateTelemetryCard(this.activeSystem);
      this.applyExplodeFactor(this.explodeFactor);
      this.render();
    }).catch((err) => {
      console.error('Failed to load GT40 model for exploded view:', err);
      if (this.loader) this.loader.classList.add('hidden');
    });
  }

  splitMeshByQuadrants(mesh, material) {
    const geo = mesh.geometry;
    const posAttr = geo.attributes.position;
    const normAttr = geo.attributes.normal;
    const uvAttr = geo.attributes.uv;
    const indices = geo.index.array;

    const buckets = { FL: [], FR: [], RL: [], RR: [] };

    for (let i = 0; i < indices.length; i += 3) {
      const i0 = indices[i];
      const i1 = indices[i + 1];
      const i2 = indices[i + 2];

      const cx = (posAttr.getX(i0) + posAttr.getX(i1) + posAttr.getX(i2)) / 3.0;
      const cz = (posAttr.getZ(i0) + posAttr.getZ(i1) + posAttr.getZ(i2)) / 3.0;

      const key = (cz >= 0 ? 'F' : 'R') + (cx >= 0 ? 'R' : 'L');
      buckets[key].push(i0, i1, i2);
    }

    const meshes = {};
    const parent = mesh.parent || this.modelRoot;

    for (const [key, idxArray] of Object.entries(buckets)) {
      if (idxArray.length === 0) continue;

      const subGeo = new THREE.BufferGeometry();
      subGeo.setAttribute('position', posAttr);
      if (normAttr) subGeo.setAttribute('normal', normAttr);
      if (uvAttr) subGeo.setAttribute('uv', uvAttr);

      subGeo.setIndex(new THREE.BufferAttribute(new Uint32Array(idxArray), 1));

      const subMesh = new THREE.Mesh(subGeo, material);
      subMesh.castShadow = true;
      subMesh.receiveShadow = true;
      subMesh.name = `${mesh.name}_${key}`;
      subMesh.userData.subsystem = 'suspension';

      parent.add(subMesh);
      meshes[key] = subMesh;
      this.interactiveMeshes.push(subMesh);
    }

    mesh.visible = false;
    return meshes;
  }

