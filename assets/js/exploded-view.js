  reassembleForReturn(durationMs = 340) {
    this.targetExplodeFactor = 0;
    this.setBrakeThermalStress(0);
    if (!this.isInitialized || this.explodeFactor <= 0.04) {
      this.explodeFactor = 0;
      if (typeof this.applyExplosion === 'function') this.applyExplosion(0);
      return Promise.resolve();
    }
    this.playPneumaticSound();
    return new Promise((resolve) => {
      const startTime = performance.now();
      const check = () => {
        if (!this.isVisible || this.explodeFactor <= 0.04 || performance.now() - startTime >= durationMs) {
          this.explodeFactor = 0;
          if (typeof this.applyExplosion === 'function') this.applyExplosion(0);
          resolve();
          return;
        }
        requestAnimationFrame(check);
      };
      requestAnimationFrame(check);
    });
  }

  setBrakeThermalStress(intensity = 0) {
    if (!this.castIronRotorMat) return;
    const clamped = Math.max(0, Math.min(1, intensity));
    if (clamped > 0.01) {
      this.castIronRotorMat.emissive.setHex(0xff3800);
      this.castIronRotorMat.emissiveIntensity = clamped * 2.5;
    } else {
      this.castIronRotorMat.emissive.setHex(0x000000);
      this.castIronRotorMat.emissiveIntensity = 0;
    }
  }

